import assert from 'node:assert/strict';
import { BackgroundAudio } from '../../entry/src/main/ets/platform/BackgroundAudio';
import { sessions, taskCalls } from './kit-background-audio';

const flush = async () => { for (let i = 0; i < 30; i++) await Promise.resolve(); };
const context = { abilityInfo: { bundleName: 'test.lumen', name: 'EntryAbility' } };
let oldPlay = 0, oldPause = 0, newPlay = 0, newPause = 0;
const first = BackgroundAudio.attach(context as never, { play: () => oldPlay++, pause: () => oldPause++ });
BackgroundAudio.update(true, true, true, first);
await flush();
assert.equal(sessions.length, 1);
const old = sessions[0];
old.emit('play'); old.emit('pause'); old.emit('stop');
assert.equal(oldPlay, 1); assert.equal(oldPause, 2);
BackgroundAudio.detach(first);
assert.equal(old.offCalls, 0, 'exit does not perform three synchronous AVSession listener-removal calls');
assert.equal(old.deactivated, true);
assert.equal(old.destroyCalls, 0, 'destruction remains async and ordered after deactivation');
old.emit('play'); old.emit('pause');
assert.equal(oldPlay, 1); assert.equal(oldPause, 2, 'retiring controls are detached immediately');

const second = BackgroundAudio.attach(context as never, { play: () => newPlay++, pause: () => newPause++ });
BackgroundAudio.update(true, true, true, second);
await flush();
assert.equal(sessions.length, 2);
old.emit('play'); old.emit('pause'); old.emit('stop');
assert.equal(newPlay, 0); assert.equal(newPause, 0, 'late old-session callbacks cannot operate the replacement room');
const current = sessions[1];
current.emit('play'); current.emit('pause');
assert.equal(newPlay, 1); assert.equal(newPause, 1);
BackgroundAudio.detach(first);
current.emit('play');
assert.equal(newPlay, 2, 'stale owner cleanup does not detach the current session');
old.completeDeactivate(); await flush();
assert.equal(old.destroyCalls, 1); assert.equal(old.offCalls, 0);
old.emit('play'); assert.equal(newPlay, 2);
BackgroundAudio.detach(second); await flush();
current.emit('play'); assert.equal(newPlay, 2);
current.completeDeactivate(); await flush();
assert.equal(current.destroyCalls, 1);
assert.equal(taskCalls.at(-1), 'stop', 'the background playback task is still retired');
console.log('Background audio: async retirement, no synchronous off calls, old/new callback isolation and owner guards passed');
